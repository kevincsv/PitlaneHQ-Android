/// English and Spanish, chosen in Settings ("system" follows the phone). Generated from the Android strings: keep both apps the same.
final class I18n: ObservableObject {
    static let shared = I18n()
    @Published var choice: String = UserDefaults.standard.string(forKey: "lang") ?? "system" {
        didSet { UserDefaults.standard.set(choice, forKey: "lang") }
    }
    var lang: String {
        if choice != "system" { return choice }
        return (Locale.preferredLanguages.first ?? "en").hasPrefix("es") ? "es" : "en"
    }
}

func t(_ key: String, _ args: CustomStringConvertible...) -> String {
    var s = strings[key].map { I18n.shared.lang == "es" ? $0.1 : $0.0 } ?? key
    for (i, a) in args.enumerated() { s = s.replacingOccurrences(of: "{\(i)}", with: a.description) }
    return s
}

