/** English and Spanish, chosen in Settings ("system" follows the phone). */
object I18n {
    var choice by mutableStateOf("system")
    val lang: String get() = if (choice == "system") (if (Locale.getDefault().language == "es") "es" else "en") else choice
}

fun t(key: String): String = STRINGS[key]?.let { if (I18n.lang == "es") it.second else it.first } ?: key

/** Text with {0}, {1}… filled in. */
fun t(key: String, vararg a: Any): String = a.foldIndexed(t(key)) { i, s, v -> s.replace("{$i}", v.toString()) }

